// Embeds drizzle/*.sql (in journal order) into src/schema/migrations.generated.ts so every runtime
// ships its migrations in code. Custom SQL (FTS, triggers) lives in drizzle/ too, via
// `drizzle-kit generate --custom`.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const journal = JSON.parse(readFileSync(path.join(root, "drizzle", "meta", "_journal.json"), "utf8"));
const migrations = journal.entries.map((entry, i) => {
  const sql = readFileSync(path.join(root, "drizzle", `${entry.tag}.sql`), "utf8");
  const statements = sql
    .split(/-->\s*statement-breakpoint/)
    .map((s) => s.trim())
    .filter(Boolean);
  return { version: i + 1, name: entry.tag, statements };
});
const out = `// Generated by scripts/embed-migrations.mjs from drizzle/*.sql. Do not edit.
import type { Migration } from "@surfingdog/platform";

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(path.join(root, "src", "schema", "migrations.generated.ts"), out);
console.log(
  `embedded ${migrations.length} migration(s), ${migrations.reduce((n, m) => n + m.statements.length, 0)} statements`,
);
